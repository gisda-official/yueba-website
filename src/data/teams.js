export const getTeam = (id) => teams.find((t) => t.id === id)

/* 工具：按分区分组 */
export const teamsByRegion = (region) => teams.filter((t) => t.region === region)

export const EAST_TEAMS = teamsByRegion('east')
export const WEST_TEAMS = teamsByRegion('west')
